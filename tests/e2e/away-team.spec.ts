import { expect, test } from '@playwright/test';
import { closeDialog, beginExpedition } from './journeys';
import { readFile } from 'node:fs/promises';
import { command, createGame, step } from '../../src/sim/game';
import { decode, encode } from '../../src/game/persistence';

test('physical wreck traversal, full-hold rejection, blocked recall, paid extraction and normal log recovery', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const state = createGame(12345);
  expect(command(state, { type: 'travel', destination: 's0-wreck', system: false }).ok).toBe(true);
  for (let i = 0; i < 140; i++) step(state);
  const wreck = state.ships.find(sh => sh.doctrine === 'derelict')!, ivo = state.crew[1];
  for (const room of wreck.rooms) { room.oxygen = .9; room.fire = 0; room.breach = 0; }
  wreck.systems.forEach(system => { system.health = system.max; });
  expect(command(state, { type: 'board', crew: ivo.id }).ok).toBe(true);
  expect(command(state, { type: 'crew', crew: ivo.id, room: wreck.rooms.find(room => room.system === 'engines')!.id, task: 'move' }).ok).toBe(true);
  for (let i = 0; i < 300 && ivo.path.length; i++) step(state);
  expect(ivo.path).toEqual([]);
  for (const door of wreck.doors) { door.open = false; door.locked = door.a === wreck.rooms[0].id || door.b === wreck.rooms[0].id; }
  state.ships[0].cargo.food = state.ships[0].capacity;
  await page.goto('/');
  await beginExpedition(page);
  await page.getByRole('button', { name: 'Skip introduction' }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.locator('input[type="file"]').setInputFiles({ name: 'blocked-wreck.json', mimeType: 'application/json', buffer: Buffer.from(encode(state)) });
  await expect(page.locator('.dialog-footer')).toContainText('Imported validated run');
  await closeDialog(page);
  await page.keyboard.press('2');
  await page.getByRole('button', { name: 'SHIP', exact: true }).click();
  await page.locator('.operation-buttons button').filter({ hasText: `${wreck.name}: Engines` }).click();
  await page.locator('.room-inspector').getByRole('button', { name: 'search', exact: true }).click();
  await page.getByRole('button', { name: /RESUME/ }).click();
  await expect(page.locator('.event-feed')).toContainText('Free 2 cargo volume', { timeout: 60000 });
  await page.locator('.pause-stack .pause-button').click();
  await page.getByRole('button', { name: 'CREW', exact: true }).click();
  await page.getByRole('button', { name: 'Recall away team', exact: true }).click();
  await expect(page.locator('.dialog-footer')).toContainText('Docking route blocked');
  await page.getByRole('button', { name: 'Emergency tether', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await expect(page.locator('[title="Credits and scrap"]')).toHaveText('CR 40');
  await closeDialog(page);
  await page.getByRole('button', { name: /RESUME/ }).click();
  await expect(page.locator('.crew-roster')).not.toContainText('AWAY', { timeout: 60000 });
  await expect(page.getByRole('progressbar', { name: 'Ivo health' })).toHaveAttribute('value', '90');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  const exported = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click();
  const download = await exported;
  expect(decode(await readFile((await download.path())!, 'utf8')).ships[0].cargo).toEqual({});
  await closeDialog(page);

  await page.getByRole('button', { name: 'CREW', exact: true }).click();
  const crew = page.locator('.service-grid article').filter({ has: page.getByRole('heading', { name: /^Ivo/ }) });
  await crew.getByRole('button', { name: 'Board contact', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toContainText('Entry O₂');
  await page.getByRole('button', { name: 'Confirm', exact: true }).click();
  await crew.getByRole('button', { name: 'Select / issue room orders', exact: true }).click();
  await page.getByRole('button', { name: 'SHIP', exact: true }).click();
  await page.locator('.dialog select').selectOption(wreck.id);
  const door = page.locator('.door-list > div').filter({ hasText: /Cockpit.*Sensors/ });
  await door.getByRole('button', { name: 'Unlock', exact: true }).click();
  await expect(door.getByRole('button', { name: 'Lock', exact: true })).toBeVisible();
  await page.locator('.operation-buttons button').filter({ hasText: `${wreck.name}: Sensors` }).click();
  await page.locator('.room-inspector').getByRole('button', { name: 'search', exact: true }).click();
  await expect(page.locator('.event-feed')).toContainText('sensor spool', { timeout: 60000 });
  await page.getByRole('button', { name: 'CREW', exact: true }).click();
  await page.getByRole('button', { name: 'Recall away team', exact: true }).click();
  await expect(page.locator('.dialog-footer')).toContainText('returning through the docking route');
  await expect(crew).toContainText('AWAY');
  await closeDialog(page);
  await expect(page.locator('.crew-roster')).not.toContainText('AWAY', { timeout: 60000 });
  await page.keyboard.press('f');
  await expect(page.locator('.command-feedback')).toContainText('saved and verified');
  expect(errors).toEqual([]);
});
